
export type ExpenseType = 'Köprü' | 'Gemi' | 'Yakıt' | 'Diğer';

/* Added 'none' to allow jobs without automated expense calculation models */
export type WorkModel = 'ist-pickup' | 'ist-dropoff' | 'saw' | 'manual' | 'none';

export interface Job {
  id: string;
  company: string;
  from: string;
  to: string;
  amount: number;
  date: string; // ISO String
  timestamp: number;
  isAutoGenerated?: boolean;
  workModel?: WorkModel; // İşin hangi modelle yapıldığını saklar
}

export interface ScheduledJob {
  id: string;
  company: string;
  passengerName: string;
  from: string;
  to: string;
  fee: number;
  date: string; // YYYY-MM-DD
  time: string; // HH:mm
}

export interface Expense {
  id: string;
  type: ExpenseType;
  amount: number;
  date: string; // ISO String
  jobId?: string; // Hangi işe ait olduğunu takip etmek için
}

export interface Stats {
  revenue: number;
  expenses: number;
  profit: number;
}

export interface TelegramConfig {
  botToken: string;
  chatId: string;
  autoSend: boolean;
}

export interface TelegramLog {
  date: string; // YYYY-MM-DD
  slot: string; // 'hour_0' ... 'hour_23' veya eski slotlar
}
